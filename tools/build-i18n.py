"""Builds the word lists i18n-en.js, i18n-fr.js, i18n-es.js, i18n-de.js from i18n/strings.json.
strings.json maps each Arabic piece of screen text to its translations: {"<arabic>": {"en":..,"fr":..,"es":..,"de":..}}.
Run after editing the app's Arabic texts:  python3 tools/build-i18n.py --check   lists new Arabic pieces that have no translation yet."""
import json, os, re, glob, sys
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S = json.load(open(os.path.join(R, 'i18n', 'strings.json'), encoding='utf-8'))
AR = re.compile(r'[\u0600-\u06FF]')
CODE = re.compile(r'\\|\.test|\.match|\.replace|\.split|const |/\*|//|=>|;|\|\||&&|\?\.|has\(|\bif\(|\belse\b|\)\s*\$')
def pieces():
    out = set()
    for f in sorted(glob.glob(os.path.join(R, '*.js'))) + [os.path.join(R, 'index.html')]:
        if os.path.basename(f) in ('sw.js',) or os.path.basename(f).startswith('i18n'): continue
        for piece in re.split(r"['\"`<>{}\n]|\$\{", open(f, encoding='utf-8').read()):
            p = re.sub(r'\s+', ' ', piece).strip()
            if AR.search(p) and len(p) <= 400 and not CODE.search(p) and not ('|' in p and '(' in p): out.add(p)
    return out
if '--check' in sys.argv:
    new = sorted(pieces() - set(S))
    print(len(new), 'Arabic pieces without a translation'); print('\n'.join(new)); sys.exit(1 if new else 0)
for L in ['en', 'fr', 'es', 'de']:
    d = {k: v[L] for k, v in S.items() if isinstance(v, dict) and isinstance(v.get(L), str) and v[L].strip()}
    with open(os.path.join(R, f'i18n-{L}.js'), 'w', encoding='utf-8') as f:
        f.write('/* generated by tools/build-i18n.py from i18n/strings.json: do not edit */\nwindow.I18N_DICT=')
        json.dump(d, f, ensure_ascii=False, separators=(',', ':')); f.write(';\n')
    print(L, len(d))
